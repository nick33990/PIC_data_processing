	@staticmethod
	def from_openPMD(directory, time_step, field, from_probes = False,\
	 dataset_name = 'fields', filename = 'simData_', species = 'p'):
		"""
		reads data from openPMD file, generated by picongpu simulation
		"""
		assert not(('n' in field) and (from_probes)), 'cannot read density from probes'


		f = h5py.File(os.path.join(directory, f"{filename}{time_step:06d}.h5"))
		f = f['data'][f'{time_step}']
		m = h5py.AttributeManager(f)
		dx, dy, _ = get_grid_steps(m, multiplier = 1e6)


		if from_probes:
			yp, xp = read_positions(f, species)
			tmp_x, tmp_y = list(set(xp)), list(set(yp))
			tmp_x, tmp_y = np.partition(tmp_x, 2)[:2], np.partition(tmp_y, 2)[:2]
			sx, sy = int(tmp_x[1] - tmp_x[0]), int(tmp_y[1] - tmp_y[0])

			x_origin = np.min(yp) * dy 
			y_origin = np.min(xp) * dx

			dx, dy = sx * dx, sy * dy
			A = read_probe_field(f, field[0], field[1],\
	 			(xp - np.min(xp)).astype('int32') // sx, (yp - np.min(yp)).astype('int32') // sy, species = species)

		else:
			A = read_field(f, field[0], field[1], dataset = dataset_name)\
			 if not 'n' in field else density_from_fields(f, field[1], dataset = dataset_name)
			x_origin, y_origin = 0, 0#A.shape[1] // 2 * dx,  A.shape[0] // 2 * dx,

		# x_origin, y_origin = 0,0 
		return xy_map(A, dx, dy, x_title = 'x, $\mu m$', y_title = 'y, $\mu m$',\
		 x_origin = x_origin, y_origin = y_origin)

