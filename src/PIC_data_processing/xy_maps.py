	@inplacify
	def to_polar_interp(self):
		"""
		transforms data from cartesian units to polar
		"""
		Ny, Nx = self.data.shape
		
		borders_x = -.5 * Nx * self.dx, .5 * Nx * self.dx
		borders_y = -.5 * Ny * self.dy, .5 * Ny * self.dy
		
		x, y = np.linspace(*borders_x, Nx), np.linspace(*borders_y, Ny)
		
		interp = RegularGridInterpolator((y, x), self.data, bounds_error = False, fill_value = 0)
		kr, theta = np.linspace(0, np.sqrt(x[-1] ** 2 + y[-1] ** 2), len(x)),\
				np.linspace(0, 2 * np.pi, len(y)) 

		kr, theta = np.meshgrid(kr, theta)
		Kx, Ky = kr * np.sin(theta), kr * np.cos(theta)
		coords = np.vstack((Kx.flatten(), Ky.flatten())).T
		theta *= 180 / np.pi
		self.data = interp(coords).reshape(Kx.shape)[::-1]
		self.dx = (kr[0, 1] - kr[0, 0]) 
		self.dy = theta[1, 0] - theta[0, 0]
		

		self.x_origin = 0
		return self

	
