def spectral_window2D(window_base_fn, shape):
	return window_base_fn(shape[0]).reshape(-1, 1) * window_base_fn(shape[1]).reshape(1, -1)


def SG_filter2D(shape, dx, dy, Rmax, order = 6, is_Fourier_space = True, as_xymap = False):
	if is_Fourier_space:
		size_x, size_y = 2 * np.pi / dx, 2 * np.pi / dy
	else:
		size_x, size_y =  shape[1] * dx, shape[0] * dy
	x = np.linspace(-0.5, 0.5, shape[1]) * size_x
	y = np.linspace(-0.5, 0.5, shape[0]) * size_y
	X, Y = np.meshgrid(x, y)
	R_sqr = X * X + Y * Y
	Filter = np.exp(-(R_sqr / (Rmax * Rmax)) ** (0.5 * order))
	if as_xymap:
		return xy_map(Filter, x[1] - x[0], y[1] - y[0], x_origin = x[0], y_origin = y[0])
	else:
		return Filter

